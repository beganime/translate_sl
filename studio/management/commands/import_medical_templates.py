class Command(BaseCommand):
    help = "Импортировать четыре медицинских шаблона и контрольные сканы"

    def add_arguments(self, parser):
        parser.add_argument("--process", action="store_true", help="Сразу обработать контрольные сканы через Gemini")

    def handle(self, *args, **options):
        root = Path(settings.BASE_DIR)
        documents = []
        for spec in TEMPLATE_SPECS:
            template_path = root / spec["template"]
            scan_path = root / spec["scan"]
            for path in (template_path, scan_path):
                if not path.exists():
                    raise CommandError(f"Не найден файл: {path}")
            template = self._upsert_template(spec, template_path)
            documents.append(self._upsert_scan(spec, template, scan_path))

        self.stdout.write(self.style.SUCCESS("Четыре медицинских шаблона и четыре контрольных скана добавлены в локальную базу."))
        if options["process"]:
            for document in documents:
                self.stdout.write(f"Обработка: {document.title}")
                process_document(document)
                document.refresh_from_db()
                self.stdout.write(self.style.SUCCESS(f"  готово: документ #{document.pk}, {len(document.extracted_data)} полей"))

    def _upsert_template(self, spec, path):
        template, _ = DocumentTemplate.objects.get_or_create(name=spec["name"])
        template.description = f"Медицинский шаблон, подготовлен из {path.name}"
        template.extraction_prompt = spec["prompt"]
        template.is_active = True
        if template.file:
            template.file.delete(save=False)
        template.file.save(path.name, ContentFile(path.read_bytes()), save=False)
        template.save()
        template.variables.all().delete()
        TemplateVariable.objects.bulk_create([
            TemplateVariable(
                template=template,
                name=name,
                label=label,
                ai_instruction=instruction,
                translate_to_russian=translate,
                required=False,
                sort_order=index * 10,
            )
            for index, (name, label, instruction, translate) in enumerate(spec["variables"], 1)
        ])
        return template

    def _upsert_scan(self, spec, template, path):
        document, _ = SourceDocument.objects.get_or_create(title=spec["title"], defaults={"template": template})
        document.template = template
        document.status = SourceDocument.Status.UPLOADED
        document.error_message = ""
        document.extracted_data = {}
        document.edited_data = {}
        if document.source_pdf:
            document.source_pdf.delete(save=False)
        document.source_pdf.save(path.name, ContentFile(path.read_bytes()), save=False)
        document.save()
        return document
